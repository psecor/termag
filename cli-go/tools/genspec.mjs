// Generates the Go CLI's command table from the Node CLI's, so the two can't
// drift: cli-go/internal/cli/spec_gen.go (every command's summary, usage,
// options, maxArgs, details and passthrough, in COMMANDS' order, plus the
// aliases and the group words), and the golden fixtures the Go tests compare
// against: every command's `--help` text and the Node parser's verdict on a
// list of command lines (testdata/help/*.txt, testdata/parse.json).
//
// Usage (from the repo root, after `npm ci` in cli/):
//   node cli-go/tools/genspec.mjs [--out <dir>]
// `make -C cli-go generate` runs it. --out writes spec_gen.go and testdata/ under <dir> instead
// of cli-go/internal/cli: TestGeneratedFilesMatchTheNodeCLI (generated_test.go) runs it that way
// and fails on any difference, so `go test ./...` catches drift (`make check-generated` runs it).
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..', '..');
const outAt = process.argv.indexOf('--out');
if (outAt >= 0 && !process.argv[outAt + 1]) throw new Error('--out needs a directory');
const outDir = outAt >= 0 ? resolve(process.argv[outAt + 1]) : join(repo, 'cli-go', 'internal', 'cli');
const cliDir = join(repo, 'cli');
const require = createRequire(join(cliDir, 'package.json'));
const { build } = require('esbuild');

// args.ts keeps ALIASES and GROUPS to itself; re-export them for this script only.
const argsSrc = readFileSync(join(cliDir, 'src', 'args.ts'), 'utf8');
// Inside cli/ so its packages (ws) resolve from cli/node_modules.
const outFile = join(cliDir, `.genspec-${process.pid}.mjs`);
await build({
  stdin: {
    contents: `${argsSrc}\nexport { ALIASES as __ALIASES, GROUPS as __GROUPS, GLOBAL_HELP as __GLOBAL_HELP };\n`,
    resolveDir: join(cliDir, 'src'),
    sourcefile: 'args.ts',
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  packages: 'external',
  outfile: outFile,
  logLevel: 'warning',
  absWorkingDir: cliDir,
});
const mod = await import(pathToFileURL(outFile).href);
rmSync(outFile, { force: true });
const { COMMANDS, GLOBAL_OPTIONS, __ALIASES: ALIASES, __GROUPS: GROUPS, __GLOBAL_HELP: GLOBAL_HELP, helpText, parseCommandLine } = mod;

const q = (s) => JSON.stringify(s); // a JSON string is a valid Go interpreted string literal for these texts
const goStr = (s) => q(s).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');

function optionsGo(options) {
  const entries = Object.entries(options ?? {});
  if (!entries.length) return 'nil';
  return `[]OptionSpec{\n${entries.map(([name, o]) =>
    `\t\t\t{Name: ${goStr(name)}, String: ${o.type === 'string'}${o.short ? `, Short: ${goStr(o.short)}` : ''}${o.multiple ? ', Multiple: true' : ''}},`).join('\n')}\n\t\t}`;
}

let go = `// Code generated by cli-go/tools/genspec.mjs from cli/src/args.ts; DO NOT EDIT.

package cli

var globalOptions = ${optionsGo(GLOBAL_OPTIONS).replace(/\n\t\t/g, '\n')}

var commandSpecs = []CommandSpec{
`;
for (const [name, spec] of Object.entries(COMMANDS)) {
  go += `\t{\n\t\tName: ${goStr(name)},\n\t\tSummary: ${goStr(spec.summary)},\n\t\tUsage: ${goStr(spec.usage)},\n`;
  go += `\t\tMaxArgs: ${spec.maxArgs === Infinity ? 'maxArgsUnlimited' : spec.maxArgs},\n`;
  if (spec.details) go += `\t\tDetails: ${goStr(spec.details)},\n`;
  if (spec.passthrough) go += `\t\tPassthrough: true,\n`;
  go += `\t\tOptions: ${optionsGo(spec.options)},\n\t},\n`;
}
go += `}\n\nvar commandAliases = map[string]string{\n`;
for (const [k, v] of Object.entries(ALIASES)) go += `\t${goStr(k)}: ${goStr(v)},\n`;
go += `}\n\nconst globalHelp = ${goStr(GLOBAL_HELP)}\n\nvar commandGroups = []string{${[...GROUPS].map(goStr).join(', ')}}\n`;
mkdirSync(outDir, { recursive: true });
const specFile = join(outDir, 'spec_gen.go');
writeFileSync(specFile, go);
try { execFileSync('gofmt', ['-w', specFile]); } catch { console.warn('gofmt not found: spec_gen.go is not formatted'); }

// Golden fixtures.
const testdata = join(outDir, 'testdata');
rmSync(join(testdata, 'help'), { recursive: true, force: true });
mkdirSync(join(testdata, 'help'), { recursive: true });
writeFileSync(join(testdata, 'help', '_top.txt'), helpText(null));
for (const name of Object.keys(COMMANDS)) writeFileSync(join(testdata, 'help', `${name.replace(/ /g, '_')}.txt`), helpText(name));

const cases = [
  [], ['--help'], ['-h'], ['--version'], ['--version', '--json'], ['help'], ['help', 'box'], ['help', 'box', 'ls'], ['help', 'space', 'memory'],
  ['help', 'nope'], ['box'], ['box', '--help'], ['env'], ['bogus'], ['box', 'bogus'], ['whoami', 'extra'], ['whoami', '--bogus'],
  ['whoami', '--json=1'], ['whoami', '--host'], ['whoami', '--host', '--json'], ['whoami', '--host=x'], ['whoami', '-x'],
  ['login', '--device', 'a', '--device', 'b'], ['ask', 'a/b', 'hi', '--from', 'x', '--from', 'y'], ['space', 'get', '-r', 'a:b'],
  ['space', 'get', '-rh'], ['space', 'ls', '--', '--json'], ['box', 'ls'], ['project', 'ls', '--json'], ['ssh', 'b', '-L', '1:localhost:1', '--json'],
  ['ssh', '--host', 'h', 'b', '--', 'ls', '-la'], ['space', 'memory', 'context', '--hook', 'SessionStart', '--refresh', '60s'],
  ['space', 'put', '-', 'x:y'], ['whoami', '-'], ['space', 'ls', '-1'], ['update', '--no-pull'], ['ask', '--inbox', '--json'],
  ['bug', 'report', '--title', 'x', '-'], ['space', 'rm', '-rf', 'x:y'], ['events', '--json', '--yes'], ['help', 'webapp-up'],
  ['webapp-up', '--help'], ['doctor', '--help'], ['whoami', '--help', 'extra', 'extra2'],
  ['feedback', '--kind', 'idea', '--', '- the sidebar is confusing'], ['feedback', '- the sidebar is confusing'],
];
const parsed = cases.map((argv) => {
  try { return { argv, result: parseCommandLine(argv) }; } catch (err) { return { argv, error: err.message, code: err.code }; }
});
writeFileSync(join(testdata, 'parse.json'), JSON.stringify(parsed, null, 2) + '\n');
console.log(`wrote spec_gen.go (${Object.keys(COMMANDS).length} commands, ${Object.keys(ALIASES).length} aliases) and testdata`);

// Fixtures for the helpers the desktop and the tables depend on: config.ts normalizeHost (the
// credentials.json key), login.ts deviceNameFrom, output.ts table/formatDate, space.ts formatBytes,
// secretPatterns.ts redactSecrets.
const helpersOut = join(cliDir, `.genspec-helpers-${process.pid}.mjs`);
await build({
  stdin: {
    contents: [
      `export { normalizeHost } from './config.ts';`,
      `export { deviceNameFrom } from './login.ts';`,
      `export { table, formatDate } from './output.ts';`,
      `export { formatBytes } from './space.ts';`,
      `export { redactSecrets } from './secretPatterns.ts';`,
    ].join('\n'),
    resolveDir: join(cliDir, 'src'), sourcefile: 'helpers.ts', loader: 'ts',
  },
  bundle: true, format: 'esm', platform: 'node', packages: 'external', outfile: helpersOut, logLevel: 'warning', absWorkingDir: cliDir,
});
const h = await import(pathToFileURL(helpersOut).href);
rmSync(helpersOut, { force: true });
