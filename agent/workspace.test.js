const { execFile } = require('child_process');
const { promisify } = require('util');
const execFileAsync = promisify(execFile);

async function git(...args) {
  return execFileAsync('git', args, { env: { ...process.env, GIT_AUTHOR_NAME: 't', GIT_AUTHOR_EMAIL: 't@t', GIT_COMMITTER_NAME: 't', GIT_COMMITTER_EMAIL: 't@t' } });
}

async function twoRepoWorkspace() {
  const root = path.join(tmp(), 'shop');
  for (const repo of ['web', 'api']) {
    await git('init', '-q', '-b', 'main', path.join(root, repo));
    await git('-C', path.join(root, repo), 'commit', '-q', '--allow-empty', '-m', 'init');
    await git('-C', path.join(root, repo), 'worktree', 'add', '-q', '-b', 'b/fix', path.join(root, '.worktrees', 'fix', repo));
  }
  fs.writeFileSync(path.join(root, '.worktrees', 'fix', 'AGENTS.md'), GUIDE);
  return root;
}

test('workspace-move renames a workstream root and every worktree in it keeps working', async () => {
  const root = await twoRepoWorkspace();
  const toDir = path.join(root, '.worktrees', 'feature');
  const guide = '<!-- Generated by termag; x -->\n# shop / feature\n';
  const result = await ws.moveWorkstreamRoot({
    root, fromDir: path.join(root, '.worktrees', 'fix'), toDir, repos: ['web', 'api'], guides: [{ dir: toDir, content: guide }],
  }, { execFile: execFileAsync });
  assert.deepEqual(result, { ok: true, moved: true, guides: 1 });
  for (const repo of ['web', 'api']) {
    assert.equal((await git('-C', path.join(toDir, repo), 'branch', '--show-current')).stdout.trim(), 'b/fix');
    assert.match((await git('-C', path.join(root, repo), 'worktree', 'list')).stdout, new RegExp(`${toDir}/${repo} `));
  }
  assert.equal(fs.readFileSync(path.join(toDir, 'AGENTS.md'), 'utf8'), guide);
  fs.rmSync(path.dirname(root), { recursive: true, force: true });
});

test('workspace-move refuses a taken name before moving, and puts the root back when a repair fails', async () => {
  const root = await twoRepoWorkspace();
  const fromDir = path.join(root, '.worktrees', 'fix');
  fs.mkdirSync(path.join(root, '.worktrees', 'taken'));
  await assert.rejects(ws.moveWorkstreamRoot({ root, fromDir, toDir: path.join(root, '.worktrees', 'taken'), repos: ['web'] }, { execFile: execFileAsync }), /already exists/);
  const failing = async (cmd, args) => {
    if (args[1].endsWith('/api') && args.some(a => a.includes('/next/'))) throw Object.assign(new Error('x'), { stderr: 'error: broken\n' });
    return execFileAsync(cmd, args);
  };
  await assert.rejects(ws.moveWorkstreamRoot({ root, fromDir, toDir: path.join(root, '.worktrees', 'next'), repos: ['web', 'api'] }, { execFile: failing }),
    /api: error: broken\); nothing was moved/);
  assert.equal(fs.existsSync(path.join(root, '.worktrees', 'next')), false);
  assert.equal((await git('-C', path.join(fromDir, 'web'), 'branch', '--show-current')).stdout.trim(), 'b/fix');
  assert.match((await git('-C', path.join(root, 'web'), 'worktree', 'list')).stdout, new RegExp(`${fromDir}/web `));
  fs.rmSync(path.dirname(root), { recursive: true, force: true });
});

test('workspace-move with no root at either place has nothing to move, and refuses paths outside .worktrees', async () => {
  const root = path.join(tmp(), 'shop');
  fs.mkdirSync(root);
  const r = await ws.moveWorkstreamRoot({ root, fromDir: path.join(root, '.worktrees', 'a'), toDir: path.join(root, '.worktrees', 'b'), repos: ['web'] }, { execFile: execFileAsync });
  assert.deepEqual(r, { ok: true, moved: false, guides: 0 });
  await assert.rejects(ws.moveWorkstreamRoot({ root, fromDir: path.join(root, 'web'), toDir: path.join(root, '.worktrees', 'b'), repos: [] }, { execFile: execFileAsync }), /under \.worktrees/);
  fs.rmSync(path.dirname(root), { recursive: true, force: true });
});

// The static layout (environment pools, task B): a multi-repo project's root on a box made from an environment is ~/code.
test('with staticRoot, the project root becomes a link to ~/code, which holds the marker and the guide', () => {
  const home = tmp();
  const dir = path.join(home, 'termag', 'projects', 'shop');
  const root = path.join(home, 'code');
  assert.deepEqual(ws.initWorkspace({ dir, guide: GUIDE, staticRoot: root, projectId: 'p1' }), { ok: true, staticLayout: true });
  assert.equal(fs.readlinkSync(dir), root);
  assert.equal(fs.existsSync(path.join(root, ws.MARKER)), true);
  assert.equal(fs.readFileSync(path.join(root, 'AGENTS.md'), 'utf8'), GUIDE);
  // Again (the next hello, a guide rewrite): still its link.
  assert.deepEqual(ws.initWorkspace({ dir, guide: GUIDE, staticRoot: root, projectId: 'p1' }), { ok: true, staticLayout: true });
  // A workstream root under it is under ~/code too.
  ws.initWorkspace({ dir: path.join(dir, '.worktrees', 'fix'), guide: GUIDE });
  assert.equal(fs.existsSync(path.join(root, '.worktrees', 'fix', 'AGENTS.md')), true);
  fs.rmSync(home, { recursive: true, force: true });
});

test('a ~/code that already holds something, or a project root already there, is never taken over', () => {
  const home = tmp();
  const root = path.join(home, 'code');
  fs.mkdirSync(path.join(root, 'mine'), { recursive: true });
  const dir = path.join(home, 'termag', 'projects', 'shop');
  const r = ws.initWorkspace({ dir, guide: GUIDE, staticRoot: root, projectId: 'p1' });
  assert.equal(r.staticLayout, false);
  assert.match(r.staticRefused, /already holds something/);
  assert.equal(fs.lstatSync(dir).isDirectory(), true, 'the per-project root, a folder');
  assert.equal(fs.existsSync(path.join(root, ws.MARKER)), false);

  const other = path.join(home, 'termag', 'projects', 'web');
  fs.mkdirSync(other, { recursive: true });
  const empty = path.join(home, 'code2');
  assert.match(ws.initWorkspace({ dir: other, guide: GUIDE, staticRoot: empty, projectId: 'p1' }).staticRefused, /already exists/);
  fs.rmSync(home, { recursive: true, force: true });
});

test("a marked ~/code another project made (one archived and renamed aside) is never this project's", () => {
  const home = tmp();
  const root = path.join(home, 'code');
  const old = path.join(home, 'termag', 'projects', 'shop');
  assert.equal(ws.initWorkspace({ dir: old, guide: GUIDE, staticRoot: root, projectId: 'p-old' }).staticLayout, true);
  fs.mkdirSync(path.join(root, 'web'));
  // Archived and renamed aside: the rename moves only the link.
  fs.renameSync(old, path.join(home, 'termag', 'projects', 'shop-archived-1'));
  const fresh = path.join(home, 'termag', 'projects', 'shop');
  const r = ws.initWorkspace({ dir: fresh, guide: '<!-- Generated by termag; new -->\n', staticRoot: root, projectId: 'p-new' });
  assert.equal(r.staticLayout, false);
  assert.match(r.staticRefused, /another project/);
  assert.equal(fs.lstatSync(fresh).isDirectory(), true, 'its own directory');
  assert.equal(fs.readFileSync(path.join(root, 'AGENTS.md'), 'utf8'), GUIDE, "the old guide isn't rewritten");
  // The project that made it gets it back (the next hello, a retry).
  fs.renameSync(path.join(home, 'termag', 'projects', 'shop-archived-1'), path.join(home, 'termag', 'projects', 'shop-old'));
  assert.equal(ws.initWorkspace({ dir: path.join(home, 'termag', 'projects', 'shop-old'), guide: GUIDE, staticRoot: root, projectId: 'p-old' }).staticLayout, true);
  fs.rmSync(home, { recursive: true, force: true });
});

