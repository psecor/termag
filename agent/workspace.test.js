test("an environment pool's prepared ~/code (marked, no owner yet) becomes the claimed project's root, and then its own", () => {
  const home = tmp();
  const root = path.join(home, 'code');
  // environment-prepare.js: the checkouts and the workspace marker, before any project.
  fs.mkdirSync(path.join(root, 'api'), { recursive: true });
  fs.writeFileSync(path.join(root, ws.MARKER), 'This directory is a termag workspace root, not a git repository.\n');
  const dir = path.join(home, 'termag', 'projects', 'shop');
  assert.deepEqual(ws.initWorkspace({ dir, guide: GUIDE, staticRoot: root, projectId: 'p1' }), { ok: true, staticLayout: true });
  assert.equal(fs.readlinkSync(dir), root);
  // Owned now: another project never takes it.
  const r = ws.initWorkspace({ dir: path.join(home, 'termag', 'projects', 'web'), guide: GUIDE, staticRoot: root, projectId: 'p2' });
  assert.match(r.staticRefused, /another project/);
  fs.rmSync(home, { recursive: true, force: true });
});
