'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { renameProject } = require('./project-rename');

function tmp() {
  return fs.mkdtempSync(path.join(os.tmpdir(), 'project-rename-'));
}

function recorder(failFor = new Set()) {
  const calls = [];
  return {
    calls,
    execFile: async (cmd, args) => {
      calls.push([cmd, ...args]);
      if (failFor.has(args[2])) throw new Error("can't find session");
    },
  };
}

test('renames each session by exact name and moves the directory', async () => {
  const root = tmp();
  fs.mkdirSync(path.join(root, 'projects', 'old'), { recursive: true });
  fs.writeFileSync(path.join(root, 'projects', 'old', 'AGENTS.md'), 'x');
  const exec = recorder();
  const result = await renameProject({
    sessions: [{ from: 'u-old-agent', to: 'u-new-agent' }, { from: 'u-old-ctrl', to: 'u-new-ctrl' }],
    fromDir: path.join(root, 'projects', 'old'),
    toDir: path.join(root, 'projects', 'new'),
  }, exec);
  assert.deepEqual(result, { ok: true, renamedSessions: 2, movedDir: true });
  assert.deepEqual(exec.calls, [
    ['tmux', 'rename-session', '-t', '=u-old-agent', '--', 'u-new-agent'],
    ['tmux', 'rename-session', '-t', '=u-old-ctrl', '--', 'u-new-ctrl'],
  ]);
  assert.equal(fs.readFileSync(path.join(root, 'projects', 'new', 'AGENTS.md'), 'utf8'), 'x');
  assert.equal(fs.existsSync(path.join(root, 'projects', 'old')), false);
});

test('skips sessions and a directory that are not there, so a retry converges', async () => {
  const root = tmp();
  fs.mkdirSync(path.join(root, 'new'));
  const exec = recorder(new Set(['=gone']));
  const result = await renameProject({
    sessions: [{ from: 'gone', to: 'x' }],
    fromDir: path.join(root, 'old'),
    toDir: path.join(root, 'new'),
  }, exec);
  assert.deepEqual(result, { ok: true, renamedSessions: 0, movedDir: false });
});

test('refuses to move onto an existing directory before renaming anything', async () => {
  const root = tmp();
  fs.mkdirSync(path.join(root, 'old'));
  fs.mkdirSync(path.join(root, 'new'));
  const exec = recorder();
  await assert.rejects(renameProject({
    sessions: [{ from: 'a', to: 'b' }],
    fromDir: path.join(root, 'old'),
    toDir: path.join(root, 'new'),
  }, exec), /already exists/);
  assert.deepEqual(exec.calls, []);
  assert.equal(fs.existsSync(path.join(root, 'old')), true);
});

test('repairs worktrees after the move', async () => {
  const root = tmp();
  fs.mkdirSync(path.join(root, 'old', '.worktrees', 'feature'), { recursive: true });
  const exec = recorder();
  await renameProject({ sessions: [], fromDir: path.join(root, 'old'), toDir: path.join(root, 'new') }, exec);
  assert.deepEqual(exec.calls, [
    ['git', '-C', path.join(root, 'new'), 'worktree', 'repair', path.join(root, 'new', '.worktrees', 'feature')],
  ]);
});

const { execFile } = require('node:child_process');
const { promisify } = require('node:util');
const execFileAsync = promisify(execFile);
const GUIDE = (title) => `<!-- Generated by termag; x -->\n# ${title}\n`;

async function git(...args) {
  return execFileAsync('git', args, { env: { ...process.env, GIT_AUTHOR_NAME: 't', GIT_AUTHOR_EMAIL: 't@t', GIT_COMMITTER_NAME: 't', GIT_COMMITTER_EMAIL: 't@t' } });
}

/** A two-repository workspace at <home>/old with a `fix` workstream holding a worktree of each. */
async function workspaceFixture() {
  const home = fs.realpathSync(tmp());
  const root = path.join(home, 'old');
  for (const repo of ['web', 'api']) {
    await git('init', '-q', '-b', 'main', path.join(root, repo));
    await git('-C', path.join(root, repo), 'commit', '-q', '--allow-empty', '-m', 'init');
    await git('-C', path.join(root, repo), 'worktree', 'add', '-q', '-b', 'e2e/fix', path.join(root, '.worktrees', 'fix', repo));
  }
  fs.writeFileSync(path.join(root, 'AGENTS.md'), GUIDE('old'));
  fs.writeFileSync(path.join(root, '.worktrees', 'fix', 'AGENTS.md'), 'hand-written\n');
  return { home, root };
}

async function status(dir) {
  return (await git('-C', dir, 'status', '--porcelain', '--branch')).stdout.split('\n')[0];
}

test('a workspace project moves with every checkout and worktree still working, and its guides rewritten', async () => {
  const { home } = await workspaceFixture();
  const to = path.join(home, 'new');
  const result = await renameProject({
    sessions: [],
    fromDir: path.join(home, 'old'),
    toDir: to,
    workspace: {
      repos: ['web', 'api'],
      guides: [{ dir: to, content: GUIDE('new') }, { dir: path.join(to, '.worktrees', 'fix'), content: GUIDE('new / fix') }],
    },
  }, { execFile: execFileAsync });
  assert.deepEqual(result, { ok: true, renamedSessions: 0, movedDir: true, guides: 1 });
  assert.equal(await status(path.join(to, 'web')), '## main');
  assert.equal(await status(path.join(to, 'api')), '## main');
  assert.equal(await status(path.join(to, '.worktrees', 'fix', 'web')), '## e2e/fix');
  assert.equal(await status(path.join(to, '.worktrees', 'fix', 'api')), '## e2e/fix');
  assert.match((await git('-C', path.join(to, 'web'), 'worktree', 'list')).stdout, new RegExp(`${to}/.worktrees/fix/web `));
  assert.equal(fs.readFileSync(path.join(to, 'AGENTS.md'), 'utf8'), GUIDE('new'));
  assert.equal(fs.readFileSync(path.join(to, '.worktrees', 'fix', 'AGENTS.md'), 'utf8'), 'hand-written\n');
});

test('a retry after the folder already moved repairs and converges', async () => {
  const { home } = await workspaceFixture();
  const to = path.join(home, 'new');
  fs.renameSync(path.join(home, 'old'), to);
  const result = await renameProject({
    sessions: [], fromDir: path.join(home, 'old'), toDir: to, workspace: { repos: ['web', 'api'] },
  }, { execFile: execFileAsync });
  assert.equal(result.movedDir, false);
  assert.equal(await status(path.join(to, '.worktrees', 'fix', 'api')), '## e2e/fix');
});

test('a failed repair puts the folder and the sessions back', async () => {
  const { home } = await workspaceFixture();
  const calls = [];
  const exec = async (cmd, args) => {
    calls.push([cmd, ...args]);
    if (cmd === 'git' && args[1].endsWith('/new/api')) {
      throw Object.assign(new Error('Command failed'), { stderr: 'repair: x\nerror: .git file broken: y\n' });
    }
    return execFileAsync(cmd, args).catch(() => {});
  };
  await assert.rejects(renameProject({
    sessions: [{ from: 'u-old-agent', to: 'u-new-agent' }],
    fromDir: path.join(home, 'old'),
    toDir: path.join(home, 'new'),
    workspace: { repos: ['web', 'api'], guides: [{ dir: path.join(home, 'new'), content: GUIDE('new') }] },
  }, { execFile: exec }), /api: error: \.git file broken: y\); nothing was renamed/);
  assert.equal(fs.existsSync(path.join(home, 'new')), false);
  assert.equal(fs.readFileSync(path.join(home, 'old', 'AGENTS.md'), 'utf8'), GUIDE('old'));
  assert.equal(await status(path.join(home, 'old', '.worktrees', 'fix', 'web')), '## e2e/fix');
  assert.deepEqual(calls.filter(c => c[0] === 'tmux'), [
    ['tmux', 'rename-session', '-t', '=u-old-agent', '--', 'u-new-agent'],
    ['tmux', 'rename-session', '-t', '=u-new-agent', '--', 'u-old-agent'],
  ]);
});

test('a single-repository project still repairs at its root', async () => {
  const root = tmp();
  fs.mkdirSync(path.join(root, 'old', '.worktrees', 'a'), { recursive: true });
  const exec = recorder();
  const result = await renameProject({ sessions: [], fromDir: path.join(root, 'old'), toDir: path.join(root, 'new') }, exec);
  assert.equal('guides' in result, false);
  assert.deepEqual(exec.calls.map(c => c.slice(0, 5)), [['git', '-C', path.join(root, 'new'), 'worktree', 'repair']]);
});
