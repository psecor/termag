'use strict';

// Multi-repo projects on the box: a workspace
// root is a plain directory holding one checkout per repository, marked by a
// file so tmux-create never git-inits it. A workstream root under
// .worktrees/<ws>/ holds a worktree of every repository.

const fs = require('fs');
const path = require('path');

// workspace-rename-v1: project-rename takes `workspace`, and workspace-move exists.
const CAPABILITIES = ['workspace-clone-v1', 'workspace-rename-v1'];
const MARKER = '.termag-workspace';
const GUIDE_HEAD = '<!-- Generated by termag';

function hasMarker(dir) {
  try {
    return fs.lstatSync(path.join(dir, MARKER)).isFile();
  } catch {
    return false;
  }
}

/** A workspace root, or a workstream root (<root>/.worktrees/<ws>) under one. */
function isWorkspaceDir(dir) {
  if (typeof dir !== 'string' || !path.isAbsolute(dir)) return false;
  if (hasMarker(dir)) return true;
  const parent = path.dirname(dir);
  return path.basename(parent) === '.worktrees' && hasMarker(path.dirname(parent));
}

function assertAbsolute(name, value) {
  if (typeof value !== 'string' || !path.isAbsolute(value) || /[\r\n\0]/.test(value)) {
    throw new Error(`${name} must be an absolute path`);
  }
}

// A guide is replaced only when termag wrote it: an AGENTS.md someone put
// there by hand is left alone.
function writeGuideFile(dir, name, content) {
  const file = path.join(dir, name);
  let current = null;
  try {
    const st = fs.lstatSync(file);
    if (!st.isFile()) return false;
    current = fs.readFileSync(file, 'utf8');
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
  }
  if (current !== null) {
    const ours = name === 'CLAUDE.md' ? current === '@AGENTS.md\n' : current.startsWith(GUIDE_HEAD);
    if (!ours) return false;
  }
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, content, { mode: 0o644 });
  fs.renameSync(tmp, file);
  return true;
}

/**
 * init-workspace: make a workspace (or workstream) root, mark it, and write its
 * generated guide. Never runs git.
 */
function initWorkspace({ dir, guide }) {
  assertAbsolute('dir', dir);
  fs.mkdirSync(dir, { recursive: true });
  // Only the project root carries the marker; a workstream root is known by its place under it.
  if (path.basename(path.dirname(dir)) !== '.worktrees' && !hasMarker(dir)) {
    fs.writeFileSync(path.join(dir, MARKER), 'This directory is a termag workspace root, not a git repository.\n');
  }
  if (typeof guide === 'string' && guide.startsWith(GUIDE_HEAD)) {
    writeGuideFile(dir, 'AGENTS.md', guide);
    writeGuideFile(dir, 'CLAUDE.md', '@AGENTS.md\n');
  }
  return { ok: true };
}

const GUIDE_FILES = new Set(['AGENTS.md', 'CLAUDE.md']);

function assertWorkstreamRoot(wsRoot) {
  assertAbsolute('wsRoot', wsRoot);
  if (path.basename(path.dirname(wsRoot)) !== '.worktrees') throw new Error('wsRoot must be under .worktrees');
}

/**
 * workspace-root-state: what a workstream root holds before it is removed.
 * `present` is the repositories whose worktree directory is there; `leftovers`
 * is everything else but the guide files, which removing the root would delete.
 */
function workstreamRootState({ wsRoot, repos }) {
  assertWorkstreamRoot(wsRoot);
  let names;
  try { names = fs.readdirSync(wsRoot); } catch (err) {
    if (err.code === 'ENOENT') return { exists: false, present: [], leftovers: [] };
    throw err;
  }
  const wanted = new Set(Array.isArray(repos) ? repos.filter(r => typeof r === 'string') : []);
  return {
    exists: true,
    present: names.filter(n => wanted.has(n)).sort(),
    leftovers: names.filter(n => !wanted.has(n) && !GUIDE_FILES.has(n)).sort(),
  };
}

/**
 * Remove a workstream root once its worktrees are gone (the guide files go
 * with it). Anything else left there refuses, unless forced.
 */
function removeWorkstreamRoot({ wsRoot, force }) {
  assertWorkstreamRoot(wsRoot);
  let names;
  try { names = fs.readdirSync(wsRoot); } catch (err) {
    if (err.code === 'ENOENT') return { ok: true, removed: false };
    throw err;
  }
  const still = names.filter(n => !GUIDE_FILES.has(n));
  if (still.length > 0 && force !== true) throw new Error(`${wsRoot} still holds ${still.join(', ')}`);
  fs.rmSync(wsRoot, { recursive: true, force: true });
  return { ok: true, removed: true };
}

function isDir(p) {
  try { return fs.statSync(p).isDirectory(); } catch { return false; }
}

function isFile(p) {
  try { return fs.lstatSync(p).isFile(); } catch { return false; }
}

/**
 * After a workspace folder moved (the project root, or one workstream root),
 * point git at the new paths: in each repository's main checkout
 * (<root>/<repo>), `git worktree repair` with its worktree in every given
 * workstream root (<wsRoot>/<repo>, those whose `.git` is a file). That fixes
 * both directions, the worktree's `.git` file and the checkout's record of
 * it, however many of them moved. A checkout that never landed is skipped.
 * Answers one line per repository git refused.
 */
async function repairWorktrees({ root, repos, wsRoots }, { execFile }) {
  const failed = [];
  for (const repo of repos) {
    const main = path.join(root, repo);
    if (!isDir(path.join(main, '.git'))) continue;
    const linked = wsRoots.map(w => path.join(w, repo)).filter(w => isFile(path.join(w, '.git')));
    if (linked.length === 0) continue;
    try {
      await execFile('git', ['-C', main, 'worktree', 'repair', ...linked]);
    } catch (err) {
      const why = String(err.stderr || err.message || err).trim().split('\n').filter(l => l.startsWith('error:')).join('; ');
      failed.push(`${repo}: ${why || String(err.message || err).trim()}`);
    }
  }
  return failed;
}

/** Every workstream root under a workspace root. */
function workstreamRoots(root) {
  const dir = path.join(root, '.worktrees');
  let names;
  try { names = fs.readdirSync(dir); } catch { return []; }
  return names.map(n => path.join(dir, n)).filter(isDir).sort();
}

/** Rewrite generated guides whose folder is there; a hand-written AGENTS.md is kept (writeGuideFile). */
function rewriteGuides(guides) {
  let written = 0;
  for (const g of Array.isArray(guides) ? guides : []) {
    if (!g || typeof g.content !== 'string' || !g.content.startsWith(GUIDE_HEAD)) continue;
    if (typeof g.dir !== 'string' || !path.isAbsolute(g.dir) || !isDir(g.dir)) continue;
    try {
      if (writeGuideFile(g.dir, 'AGENTS.md', g.content)) written++;
      writeGuideFile(g.dir, 'CLAUDE.md', '@AGENTS.md\n');
    } catch { /* a guide is not worth failing a rename over */ }
  }
  return written;
}

function repoNames(repos) {
  return (Array.isArray(repos) ? repos : []).filter(r => typeof r === 'string' && /^[A-Za-z0-9][A-Za-z0-9_-]*$/.test(r));
}

/**
 * workspace-move: rename a workstream of a multi-repo project. Its root moves
 * from <root>/.worktrees/<from> to <root>/.worktrees/<to>, each repository's
 * worktree in it is repaired, and its guide rewritten. A failed repair moves
 * the root back and repairs again, so the call either did it all or nothing.
 * A root already at `toDir` (an earlier call got that far) is only repaired,
 * and one at neither place is nothing to move.
 */
async function moveWorkstreamRoot({ root, fromDir, toDir, repos, guides }, { execFile }) {
  assertAbsolute('root', root);
  assertWorkstreamRoot(fromDir);
  assertWorkstreamRoot(toDir);
  if (path.dirname(fromDir) !== path.join(root, '.worktrees') || path.dirname(toDir) !== path.join(root, '.worktrees')) {
    throw new Error('fromDir and toDir must be under root/.worktrees');
  }
  const names = repoNames(repos);
  const fromThere = fs.existsSync(fromDir);
  if (fromThere && fs.existsSync(toDir)) throw new Error(`${toDir} already exists`);
  if (fromThere) fs.renameSync(fromDir, toDir);
  const failed = await repairWorktrees({ root, repos: names, wsRoots: [toDir] }, { execFile });
  if (failed.length > 0) {
    const why = `git worktree repair failed (${failed.join('; ')})`;
    if (!fromThere) throw new Error(`${why}; the workstream folder is at ${toDir}`);
    try {
      fs.renameSync(toDir, fromDir);
    } catch (err) {
      throw new Error(`${why}, and moving it back failed (${err.message}); the workstream folder is at ${toDir}`);
    }
    await repairWorktrees({ root, repos: names, wsRoots: [fromDir] }, { execFile });
    throw new Error(`${why}; nothing was moved`);
  }
  return { ok: true, moved: fromThere, guides: rewriteGuides(guides) };
}

/** tmux-create's git init: not in a repository already, not opted out, and never in a workspace or workstream root. */
function shouldGitInit(cwd, { alreadyRepo, gitInit }) {
  return !alreadyRepo && gitInit !== false && !isWorkspaceDir(cwd);
}

module.exports = {
  CAPABILITIES,
  MARKER,
  isWorkspaceDir,
  initWorkspace,
  workstreamRootState,
  removeWorkstreamRoot,
  repairWorktrees,
  workstreamRoots,
  rewriteGuides,
  repoNames,
  moveWorkstreamRoot,
  shouldGitInit,
};
